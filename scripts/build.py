def build_package_module(onto: Graph, cat: dict, package: dict) -> Graph:
    """The part of the ontology that belongs to one package, as a stand-alone Turtle module.

    It holds the package's classes, the properties whose domain is one of them, and the
    SKOS vocabularies typed by them. Terms of other packages are referenced by IRI but not
    redefined; the full ontology is ontology/src/aro.ttl.
    """
    names = {c["name"] for c in cat["classes"] if c["package"] == package["name"]}
    subjects = {ARO[n] for n in names}

    def in_package(ref):
        return (ref in names) if isinstance(ref, str) else any(r in names for r in ref)

    subjects |= {ARO[r["name"]] for r in cat["relations"] if in_package(r["source"])}
    subjects |= {ARO[d["name"]] for d in cat.get("datatype_properties", []) if d.get("domain") and in_package(d["domain"])}
    for scheme in cat.get("concept_schemes", []):
        if scheme.get("member_class") in names:
            subjects.add(ARO[scheme["name"]])
            subjects |= {ARO[c["name"]] for c in scheme["concepts"]}
    g = bind(Graph())
    module = module_iri(package["name"])
    g.add((module, RDF.type, OWL.Ontology))
    g.add((module, DCTERMS.isPartOf, ONTOLOGY_IRI))
    g.add((module, OWL.versionInfo, Literal(cat["version"])))
    g.add((module, DCTERMS.title, Literal(f"ARO module: {package['label_en']}", lang="en")))
    g.add((module, DCTERMS.title, Literal(f"Módulo ARO: {package['label_pt']}", lang="pt-BR")))
    g.add((module, DCTERMS.description, Literal(package["description_en"], lang="en")))
    g.add((module, DCTERMS.description, Literal(package["description_pt"], lang="pt-BR")))
    # copy the subjects' triples, following blank nodes (owl:unionOf lists) recursively
    stack = list(subjects)
    seen = set()
    while stack:
        s = stack.pop()
        if s in seen:
            continue
        seen.add(s)
        for _, p, o in onto.triples((s, None, None)):
            g.add((s, p, o))
            if isinstance(o, BNode):
                stack.append(o)
    return g


def make_release(cat: dict) -> int:
    """Freeze the development version into releases/v<version>/ (never overwrites)."""
    version = cat["version"]
    target = RELEASES / f"v{version}"
    if target.exists():
        print(f"releases/v{version}/ already exists; releases are immutable. Bump the version in the catalog first.")
        return 1
    if not all_up_to_date(cat):
        print("Run python scripts/build.py first: generated files are out of date.")
        return 1
    target.mkdir(parents=True)
    for name in ("aro.ttl", "aro.owl", "aro.jsonld"):
        shutil.copyfile(SRC / name, target / name)
    shutil.copyfile(ROOT / "validation/aro-shapes.ttl", target / "aro-shapes.ttl")
    shutil.copytree(SRC / "modules", target / "modules")
    (target / "RELEASE-NOTES.md").write_text(
        f"# ARO {version}\n\n## English\n\n(Describe this release.)\n\n## Português\n\n(Descreva esta versão.)\n",
        encoding="utf-8", newline="\n")
    print(f"Created releases/v{version}/. Edit its RELEASE-NOTES.md and list it in releases/README.md and CHANGELOG.md.")
    return 0


def all_up_to_date(cat: dict) -> bool:
    """True when every generated file matches the catalog."""
    return all(path.exists() and same_content(path, path.read_text(encoding="utf-8"), text)
               for path, text in outputs(cat).items())


def with_turtle_header(text: str) -> str:
    """Prefix a Turtle serialization with the generated-file notice (Turtle comments start with #)."""
    return f"# {GENERATED_NOTE}\n{text}"


def with_xml_header(text: str) -> str:
    """Insert the generated-file notice as an XML comment right after the XML declaration."""
    decl, rest = text.split("\n", 1)
    return f"{decl}\n<!-- {GENERATED_NOTE} -->\n{rest}"


