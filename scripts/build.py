"""Generate every derived ARO artifact from model/conceptual-model.json.

The conceptual catalog is the single source of truth (ADR-017). This script writes:
  ontology/src/aro.ttl, .owl, .jsonld                          OWL vocabulary (development version)
  ontology/src/modules/<package>.ttl                           one module file per package
  validation/aro-shapes.ttl                                    SHACL constraints
  schemas/record.schema.json                                   generic record JSON Schema
  schemas/derivation-annotation.schema.json                    annotator exchange JSON Schema
  docs/en/reference-model.md, docs/pt-BR/reference-model.md   bilingual reference documentation
  README.md, LEIA-ME.md                                        only the marked class-overview section
  model/diagrams/*.dot (and *.svg when Graphviz `dot` is available)
  queries/index.json                                           list of CQ/RQ queries for the annotator
  model/diagrams/ontouml/*.dot, *.svg                           OntoUML class diagrams (overview + per package)

Usage:
  python scripts/build.py            # regenerate files that changed and render outdated SVGs
  python scripts/build.py --check    # exit 1 if any generated file differs from the catalog (used by tests)
  python scripts/build.py --release  # freeze the current version into releases/v<version>/

Releases are immutable: --release refuses to overwrite an existing releases/v<version>/.

To change the model, edit the catalog and run this script; never edit generated files by hand.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

from rdflib import BNode, Graph, Literal, Namespace, URIRef
from rdflib.collection import Collection
from rdflib.namespace import DCTERMS, OWL, RDF, RDFS, SKOS, XSD

# Repository paths
ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "model" / "conceptual-model.json"

# ARO namespace (term IRIs) and the IRI of the ontology document itself
ARO = Namespace("https://w3id.org/aro/ontology#")
ONTOLOGY_IRI = URIRef("https://w3id.org/aro/ontology")
SRC = ROOT / "ontology" / "src"          # development version of the ontology
RELEASES = ROOT / "releases"             # frozen versions, one folder per version


def module_iri(package: str) -> URIRef:
    """IRI of one module (package) of the ontology, e.g. https://w3id.org/aro/ontology/module/artwork."""
    return URIRef(f"{ONTOLOGY_IRI}/module/{package}")


def version_iri(version: str) -> URIRef:
    """IRI of one version of the ontology (owl:versionIRI), e.g. https://w3id.org/aro/ontology/0.2.0-beta."""
    return URIRef(f"{ONTOLOGY_IRI}/{version}")

# External vocabularies referenced by the catalog (SHACL, alignments, selectors, agents)
SH = Namespace("http://www.w3.org/ns/shacl#")
PROV = Namespace("http://www.w3.org/ns/prov#")
SCHEMA = Namespace("https://schema.org/")
WDT = Namespace("http://www.wikidata.org/prop/direct/")
FOAF = Namespace("http://xmlns.com/foaf/0.1/")
OA = Namespace("http://www.w3.org/ns/oa#")
LRMOO = Namespace("http://iflastandards.info/ns/lrm/lrmoo/")

# Prefixes accepted in catalog values such as "prov:wasDerivedFrom" or "rdf:langString"
PREFIXES = {"skos": SKOS, "owl": OWL, "rdfs": RDFS, "xsd": XSD, "dcterms": DCTERMS,
            "prov": PROV, "schema": SCHEMA, "wdt": WDT, "foaf": FOAF, "oa": OA, "rdf": RDF, "lrmoo": LRMOO}

# Header placed at the top of generated text files that support comments
GENERATED_NOTE = "Generated by scripts/build.py from model/conceptual-model.json. Do not edit by hand."


def load_catalog() -> dict:
    """Read the conceptual catalog (always UTF-8, independent of the OS locale)."""
    return json.loads(CATALOG.read_text(encoding="utf-8"))


def parents(c: dict) -> list[str]:
    """Superclasses of a catalog class: `specializes` may be one name or a list (a role of a kind and a roleMixin)."""
    sp = c.get("specializes")
    return [] if not sp else ([sp] if isinstance(sp, str) else list(sp))


# Rigid sortals: each individual instantiates exactly one ultimate sortal (UFO), so the
# top-level ones are pairwise disjoint; subkinds partition their abstract parent.
ULTIMATE_SORTALS = ("kind", "collective", "event", "situation", "relator", "type")
RIGID_SORTALS = ULTIMATE_SORTALS + ("subkind",)


def iri(term: str) -> URIRef:
    """Resolve a catalog term to an IRI.

    Accepts a prefixed name ("skos:Concept"), a full IRI ("https://..."), or a bare
    local name, which is taken to be an ARO term ("Artwork" -> aro:Artwork).
    """
    if ":" in term and not term.startswith("http"):
        prefix, local = term.split(":", 1)
        return PREFIXES[prefix][local]
    if term.startswith("http"):
        return URIRef(term)
    return ARO[term]


def bind(g: Graph) -> Graph:
    """Register readable prefixes so serializations use aro:, skos:, prov: ... instead of full IRIs."""
    g.bind("aro", ARO)
    for prefix in ("dcterms", "owl", "rdfs", "skos", "xsd", "prov", "schema", "wdt", "foaf", "oa", "lrmoo"):
        g.bind(prefix, PREFIXES[prefix])
    return g


# --------------------------------------------------------------------------- OWL
def build_ontology(cat: dict) -> Graph:
    """Project the catalog into an OWL 2 vocabulary.

    Language policy (ADR-024): every term is identified in English and carries
    labels, definitions and comments in both English (@en) and Brazilian Portuguese (@pt-BR).
    """
    g = bind(Graph())

    # Ontology header: bilingual title/description and version
    g.add((ONTOLOGY_IRI, RDF.type, OWL.Ontology))
    meta = cat["ontology"]
    for key, prop in (("title", DCTERMS.title), ("description", DCTERMS.description)):
        g.add((ONTOLOGY_IRI, prop, Literal(meta[f"{key}_en"], lang="en")))
        g.add((ONTOLOGY_IRI, prop, Literal(meta[f"{key}_pt"], lang="pt-BR")))
    g.add((ONTOLOGY_IRI, OWL.versionInfo, Literal(cat["version"])))
    # Versioning: this version's IRI and the previous release
    g.add((ONTOLOGY_IRI, OWL.versionIRI, version_iri(cat["version"])))
    if meta.get("prior_version"):
        g.add((ONTOLOGY_IRI, OWL.priorVersion, version_iri(meta["prior_version"])))
    # Authorship and academic affiliation (doctoral project)
    if meta.get("creator"):
        g.add((ONTOLOGY_IRI, DCTERMS.creator, Literal(meta["creator"])))
    for person in meta.get("contributors", []):
        g.add((ONTOLOGY_IRI, DCTERMS.contributor, Literal(person)))
    if meta.get("affiliation_en"):
        g.add((ONTOLOGY_IRI, RDFS.comment, Literal(meta["affiliation_en"], lang="en")))
        g.add((ONTOLOGY_IRI, RDFS.comment, Literal(meta["affiliation_pt"], lang="pt-BR")))

    # Modules: each package is a module with a label and a description of what it covers;
    # every class and relation states its module with rdfs:isDefinedBy
    for pkg in cat["packages"]:
        m = module_iri(pkg["name"])
        g.add((ONTOLOGY_IRI, DCTERMS.hasPart, m))
        g.add((m, RDFS.label, Literal(pkg["label_en"], lang="en")))
        g.add((m, RDFS.label, Literal(pkg["label_pt"], lang="pt-BR")))
        g.add((m, DCTERMS.description, Literal(pkg["description_en"], lang="en")))
        g.add((m, DCTERMS.description, Literal(pkg["description_pt"], lang="pt-BR")))
    package_of = {c["name"]: c["package"] for c in cat["classes"]}

    # Classes: label, definition and a comment recording the provisional OntoUML
    # stereotype, UFO grounding and existential dependency, in both languages
    for c in cat["classes"]:
        s = ARO[c["name"]]
        g.add((s, RDF.type, OWL.Class))
        g.add((s, RDFS.label, Literal(c["label_en"], lang="en")))
        g.add((s, RDFS.label, Literal(c["label_pt"], lang="pt-BR")))
        g.add((s, RDFS.comment, Literal(
            f"OntoUML stereotype (provisional): {c['stereotype']}; foundation: {c['grounding_en']}; "
            f"dependency: {c['dependency_en']}", lang="en")))
        g.add((s, RDFS.comment, Literal(
            f"Estereótipo OntoUML (provisório): {c['stereotype']}; fundamentação: {c['grounding_pt']}; "
            f"dependência: {c['dependency_pt']}", lang="pt-BR")))
        g.add((s, SKOS.definition, Literal(c["definition_en"], lang="en")))
        g.add((s, SKOS.definition, Literal(c["definition_pt"], lang="pt-BR")))
        g.add((s, RDFS.isDefinedBy, module_iri(c["package"])))
        for sup in parents(c):
            g.add((s, RDFS.subClassOf, ARO[sup]))
        # a role of a kind that specializes a roleMixin is exactly their intersection
        # (e.g. PersonAnalyst = Person and Analyst), so a reasoner can classify it
        if len(parents(c)) > 1:
            inter = BNode()
            g.add((inter, RDF.type, OWL.Class))
            members = BNode()
            Collection(g, members, [ARO[x] for x in parents(c)])
            g.add((inter, OWL.intersectionOf, members))
            g.add((s, OWL.equivalentClass, inter))
        # Alignments are non-committal links (e.g. rdfs:seeAlso), never equivalences
        for prop, targets in c.get("alignments", {}).items():
            for t in targets:
                g.add((s, iri(prop), iri(t)))

    # UFO commitments OWL can express: ultimate sortals are pairwise disjoint, and an
    # abstract class (a category, or a kind/subkind fully divided into subkinds) is the
    # disjoint union of its rigid sortal children
    by_name = {c["name"]: c for c in cat["classes"]}
    ultimate = [c["name"] for c in cat["classes"] if c["stereotype"] in ULTIMATE_SORTALS]
    if len(ultimate) > 1:
        dis = BNode()
        g.add((dis, RDF.type, OWL.AllDisjointClasses))
        members = BNode()
        Collection(g, members, [ARO[x] for x in ultimate])
        g.add((dis, OWL.members, members))
    for c in cat["classes"]:
        children = [k["name"] for k in cat["classes"] if c["name"] in parents(k) and k["stereotype"] in RIGID_SORTALS]
        if c.get("abstract") and children:
            members = BNode()
            Collection(g, members, [ARO[x] for x in children])
            g.add((ARO[c["name"]], OWL.disjointUnionOf, members))
        elif len([x for x in children if by_name[x]["stereotype"] == "subkind"]) > 1:
            subs = [x for x in children if by_name[x]["stereotype"] == "subkind"]
            dis = BNode()
            g.add((dis, RDF.type, OWL.AllDisjointClasses))
            members = BNode()
            Collection(g, members, [ARO[x] for x in subs])
            g.add((dis, OWL.members, members))

    # Object properties: domain/range may be a single class, an external class
    # (e.g. oa:Selector) or a list of classes, which becomes an owl:unionOf
    for r in cat["relations"]:
        p = ARO[r["name"]]
        g.add((p, RDF.type, OWL.ObjectProperty))
        g.add((p, RDFS.label, Literal(r["description_en"], lang="en")))
        g.add((p, RDFS.label, Literal(r["description_pt"], lang="pt-BR")))
        # what the relation is for, in both languages
        g.add((p, SKOS.definition, Literal(r["definition_en"], lang="en")))
        g.add((p, SKOS.definition, Literal(r["definition_pt"], lang="pt-BR")))
        source = r["source"] if isinstance(r["source"], str) else r["source"][0]
        if source in package_of:
            g.add((p, RDFS.isDefinedBy, module_iri(package_of[source])))
        g.add((p, RDFS.domain, class_expr(g, r["source"])))
        g.add((p, RDFS.range, class_expr(g, r["target"])))
        if r.get("inverse_of"):
            g.add((p, OWL.inverseOf, ARO[r["inverse_of"]]))
        if r.get("specializes"):
            g.add((p, RDFS.subPropertyOf, ARO[r["specializes"]]))
        for prop, targets in r.get("alignments", {}).items():
            for t in targets:
                g.add((p, iri(prop), iri(t)))

    # Datatype properties: XSD ranges by local name ("string"), other datatypes
    # by prefixed name ("rdf:langString" for multilingual content)
    for d in cat.get("datatype_properties", []):
        p = ARO[d["name"]]
        g.add((p, RDF.type, OWL.DatatypeProperty))
        g.add((p, RDFS.range, iri(d["range"]) if ":" in d["range"] else XSD[d["range"]]))
        g.add((p, RDFS.label, Literal(d["label_en"], lang="en")))
        g.add((p, RDFS.label, Literal(d["label_pt"], lang="pt-BR")))
        g.add((p, RDFS.comment, Literal(d["comment_en"], lang="en")))
        g.add((p, RDFS.comment, Literal(d["comment_pt"], lang="pt-BR")))
        if d.get("domain"):
            g.add((p, RDFS.domain, class_expr(g, d["domain"])))

    # Controlled vocabularies (derivation types, dimensions, roles...)
    for scheme in cat.get("concept_schemes", []):
        add_concept_scheme(g, scheme)
    return g


def class_expr(g: Graph, ref: str | list[str]):
    """A single class reference, or a list rendered as an anonymous owl:unionOf class."""
    if isinstance(ref, str):
        return iri(ref)
    union = BNode()
    g.add((union, RDF.type, OWL.Class))
    members = BNode()
    Collection(g, members, [iri(x) for x in ref])  # RDF list of the member classes
    g.add((union, OWL.unionOf, members))
    return union


def add_concept_scheme(g: Graph, scheme: dict) -> None:
    """Emit one SKOS concept scheme and its concepts.

    Each concept is both a skos:Concept and an instance of the scheme's high-order
    ARO class (member_class, e.g. aro:DerivationType), so SHACL can check that a
    claim points to a concept of the right vocabulary. Concepts without `broader`
    become top concepts; `source` records the literature that grounds the concept.
    """
    s = ARO[scheme["name"]]
    g.add((s, RDF.type, SKOS.ConceptScheme))
    g.add((s, SKOS.prefLabel, Literal(scheme["label_en"], lang="en")))
    g.add((s, SKOS.prefLabel, Literal(scheme["label_pt"], lang="pt-BR")))
    if scheme.get("definition_en"):
        g.add((s, SKOS.definition, Literal(scheme["definition_en"], lang="en")))
    if scheme.get("definition_pt"):
        g.add((s, SKOS.definition, Literal(scheme["definition_pt"], lang="pt-BR")))
    for c in scheme["concepts"]:
        cs = ARO[c["name"]]
        g.add((cs, RDF.type, SKOS.Concept))
        if scheme.get("member_class"):
            g.add((cs, RDF.type, ARO[scheme["member_class"]]))
        g.add((cs, SKOS.inScheme, s))
        g.add((cs, SKOS.prefLabel, Literal(c["label_en"], lang="en")))
        g.add((cs, SKOS.prefLabel, Literal(c["label_pt"], lang="pt-BR")))
        g.add((cs, SKOS.definition, Literal(c["definition_en"], lang="en")))
        g.add((cs, SKOS.definition, Literal(c["definition_pt"], lang="pt-BR")))
        if c.get("source"):
            g.add((cs, DCTERMS.source, Literal(c["source"])))
        if c.get("broader"):
            g.add((cs, SKOS.broader, ARO[c["broader"]]))
        else:
            g.add((cs, SKOS.topConceptOf, s))
            g.add((s, SKOS.hasTopConcept, cs))


# ------------------------------------------------------------------------- SHACL
def build_shapes(cat: dict) -> Graph:
    """Build the SHACL constraints that OWL's open-world semantics cannot enforce.

    Three kinds of shapes are produced:
      1. property shapes from each relation's `shacl` entry (cardinality, class, node kind);
      2. language shapes for datatype properties that must hold language-tagged text;
      3. SHACL-SPARQL constraints from `sparql_constraints` (e.g. distinct derivation anchors).
    """
    g = Graph()
    g.bind("aro", ARO)
    g.bind("sh", SH)
    g.bind("xsd", XSD)

    # 1. Group constrained relations by their domain class: one NodeShape per class
    # A relation's `shacl` applies to its domain class; `shacl_by_class` adds constraints
    # that hold only for some subclasses (e.g. producedByAct is required on InterpretationRecord)
    by_class: dict[str, list[tuple[dict, dict]]] = {}
    for r in cat["relations"]:
        if r.get("shacl"):
            if not isinstance(r["source"], str):
                raise ValueError(f"SHACL constraint on union-domain relation {r['name']} is unsupported")
            by_class.setdefault(r["source"], []).append((r, r["shacl"]))
        for cls, constraint in r.get("shacl_by_class", {}).items():
            by_class.setdefault(cls, []).append((r, constraint))
    for cls, rels in by_class.items():
        node = ARO[f"{cls}Shape"]
        g.add((node, RDF.type, SH.NodeShape))
        g.add((node, SH.targetClass, ARO[cls]))
        for r, constraint in rels:
            ps = ARO[f"{cls}{r['name']}PropertyShape"]
            g.add((node, SH.property, ps))
            g.add((ps, SH.path, ARO[r["name"]]))
            for key in ("minCount", "maxCount"):
                if key in constraint:
                    g.add((ps, SH[key], Literal(constraint[key])))
            if constraint.get("class"):          # value must be an instance of this class
                g.add((ps, SH["class"], ARO[constraint["class"]]))
            if constraint.get("nodeKind"):       # e.g. IRI: external agents must be linkable
                g.add((ps, SH.nodeKind, SH[constraint["nodeKind"]]))

    # 2. Multilingual content: any resource using the property must give language-tagged values
    for d in cat.get("datatype_properties", []):
        if d.get("shacl", {}).get("datatype"):
            node = ARO[f"{d['name']}LanguageShape"]
            g.add((node, RDF.type, SH.NodeShape))
            g.add((node, SH.targetSubjectsOf, ARO[d["name"]]))
            ps = ARO[f"{d['name']}DatatypePropertyShape"]
            g.add((node, SH.property, ps))
            g.add((ps, SH.path, ARO[d["name"]]))
            g.add((ps, SH.datatype, iri(d["shacl"]["datatype"])))
            g.add((ps, SH.message, Literal(f"{d['name']} values must be language-tagged literals.", lang="en")))
            g.add((ps, SH.message, Literal(f"Valores de {d['name']} devem ser literais marcados por idioma.", lang="pt-BR")))

    # 2b. Values limited to a set of datatypes (e.g. dates given as a year, a month, a day or a moment)
    for d in cat.get("datatype_properties", []):
        types = d.get("shacl", {}).get("datatypes")
        if types:
            node = ARO[f"{d['name']}DatatypeShape"]
            g.add((node, RDF.type, SH.NodeShape))
            g.add((node, SH.targetSubjectsOf, ARO[d["name"]]))
            ps = ARO[f"{d['name']}DatatypesPropertyShape"]
            g.add((node, SH.property, ps))
            g.add((ps, SH.path, ARO[d["name"]]))
            alternatives = []
            for t in types:
                alt = BNode()
                g.add((alt, SH.datatype, iri(t)))
                alternatives.append(alt)
            head = BNode()
            Collection(g, head, alternatives)
            g.add((ps, SH["or"], head))
            names = ", ".join(types)
            g.add((ps, SH.message, Literal(f"{d['name']} values must be one of: {names}.", lang="en")))
            g.add((ps, SH.message, Literal(f"Valores de {d['name']} devem ser de um destes tipos: {names}.", lang="pt-BR")))

    # 2c. Values from a closed list (e.g. the outcome of an assessment), at most `maxCount` values
    for d in cat.get("datatype_properties", []):
        allowed = d.get("shacl", {}).get("in")
        if allowed:
            node = ARO[f"{d['name']}ValueShape"]
            g.add((node, RDF.type, SH.NodeShape))
            g.add((node, SH.targetSubjectsOf, ARO[d["name"]]))
            ps = ARO[f"{d['name']}ValuesPropertyShape"]
            g.add((node, SH.property, ps))
            g.add((ps, SH.path, ARO[d["name"]]))
            head = BNode()
            Collection(g, head, [Literal(v) for v in allowed])
            g.add((ps, SH["in"], head))
            if "maxCount" in d["shacl"]:
                g.add((ps, SH.maxCount, Literal(d["shacl"]["maxCount"])))
            names = ", ".join(allowed)
            g.add((ps, SH.message, Literal(f"{d['name']} must be one of: {names}.", lang="en")))
            g.add((ps, SH.message, Literal(f"{d['name']} deve ser um destes valores: {names}.", lang="pt-BR")))

    # 3. SPARQL-based constraints, with bilingual violation messages
    for sparql in cat.get("sparql_constraints", []):
        node = ARO[f"{sparql['target']}Shape"]
        g.add((node, RDF.type, SH.NodeShape))
        g.add((node, SH.targetClass, ARO[sparql["target"]]))
        c = ARO[sparql["name"]]
        g.add((node, SH.sparql, c))
        g.add((c, RDF.type, SH.SPARQLConstraint))
        g.add((c, SH.message, Literal(sparql["message_en"], lang="en")))
        g.add((c, SH.message, Literal(sparql["message_pt"], lang="pt-BR")))
        g.add((c, SH.select, Literal(sparql["select"])))
        g.add((c, SH.prefixes, ARO["prefixes"]))
    # SHACL-SPARQL queries resolve the aro: prefix through this declaration
    if cat.get("sparql_constraints"):
        decl = BNode()
        g.add((ARO["prefixes"], SH.declare, decl))
        g.add((decl, SH.prefix, Literal("aro")))
        g.add((decl, SH.namespace, Literal(str(ARO), datatype=XSD.anyURI)))
    return g


# ------------------------------------------------------------------- JSON Schema
def build_record_schema(cat: dict) -> dict:
    """Generic exchange record: any ARO class name is an accepted `type`."""
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": GENERATED_NOTE,
        "title": "ARO generic record",
        "type": "object",
        "required": ["id", "type"],
        "properties": {
            "id": {"type": "string"},
            "type": {"enum": [c["name"] for c in cat["classes"]]},
            "label": {"type": "string"},
            "description": {"type": "string"},
            "references": {"type": "array", "items": {"type": "string"}},
        },
        "additionalProperties": True,
    }


