def build_dot(cat: dict, package: str | None) -> str:
    """Render a DOT diagram for the overview (package=None) or a single package.

    Nodes are coloured by package and labelled «stereotype» + name; edges show the
    relation name and target multiplicity; dashed arrows with hollow heads are
    specializations. Packages flagged show_context also draw the classes from other
    packages that their relations reach, with dashed borders. External classes
    (e.g. oa:Selector) are not drawn.
    """
    colors = {p["name"]: p["color"] for p in cat["packages"]}
    classes = [c for c in cat["classes"] if package is None or c["package"] == package]
    names = {c["name"] for c in classes}
    context: list[dict] = []
    if package and next(p for p in cat["packages"] if p["name"] == package).get("show_context"):
        reached = set()
        for r in cat["relations"]:
            ends = [r["source"]] if isinstance(r["source"], str) else r["source"]
            ends += [r["target"]] if isinstance(r["target"], str) else r["target"]
            if names & set(ends):
                reached |= set(ends) - names
        context = [c for c in cat["classes"] if c["name"] in reached]
    lines = [DOT_HEADER]
    for c in classes:
        lines.append(f'"{c["name"]}" [label="«{c["stereotype"]}»\\n{c["name"]}",fillcolor="{colors[c["package"]]}"];')
    for c in context:
        lines.append(f'"{c["name"]}" [label="«{c["stereotype"]}»\\n{c["name"]}",fillcolor="{colors[c["package"]]}",style="rounded,filled,dashed"];')
    names |= {c["name"] for c in context}
    # Union domains/ranges are drawn as one edge per member class
    for r in cat["relations"]:
        sources = [r["source"]] if isinstance(r["source"], str) else r["source"]
        targets = [r["target"]] if isinstance(r["target"], str) else r["target"]
        for s in sources:
            for tgt in targets:
                if s in names and tgt in names:
                    lines.append(f'"{s}" -> "{tgt}" [label="{r["name"]}  [{r["target_cardinality"]}]",arrowsize=.65];')
    for c in classes:
        for sup in parents(c):
            if sup in names:
                lines.append(f'"{c["name"]}" -> "{sup}" [arrowhead=empty,style=dashed];')
    lines.append("}")
    return "\n".join(lines)


MODULE_LANGS = {"en": "en", "pt-BR": "pt"}   # file suffix -> catalog field suffix


def build_module_dot(cat: dict, lang: str) -> str:
    """Render the module map shown in README/LEIA-ME.

    Each package is a coloured cluster titled in the given language; only the classes
    touched by the relations listed in `module_diagram` are drawn. A relation whose
    range is a union of classes from one package (e.g. the derivation anchors) is drawn
    as a single edge ending at that package's border (Graphviz `lhead`).
    """
    suffix = MODULE_LANGS[lang]
    pkg_of = {c["name"]: c["package"] for c in cat["classes"]}
    rels = {r["name"]: r for r in cat["relations"]}
    chosen = [rels[n] for n in cat["module_diagram"]["relations"]]

    def ends(ref):
        return [ref] if isinstance(ref, str) else list(ref)

    # Classes to draw: every ARO class at either end of a chosen relation
    drawn = {x for r in chosen for x in ends(r["source"]) + ends(r["target"]) if x in pkg_of}
    lines = [f"// {GENERATED_NOTE}", "digraph modules {",
             'graph [rankdir=LR, compound=true, bgcolor="white", pad="0.3", nodesep="0.3", ranksep="0.9", '
             'fontname="Arial", fontsize=13, labeljust="l", newrank=true];',
             'node [shape=box, style="rounded,filled", color="#475569", fillcolor="white", fontname="Arial", fontsize=10];',
             'edge [color="#64748b", fontname="Arial", fontsize=8, arrowsize=.6];']
    for p in cat["packages"]:
        members = [c for c in cat["classes"] if c["package"] == p["name"] and c["name"] in drawn]
        if not members:
            continue
        lines.append(f'subgraph "cluster_{p["name"]}" {{')
        lines.append(f'label="{p["label_" + suffix]}"; style="rounded,filled"; fillcolor="{p["color"]}"; color="{p["color"]}";')
        for c in members:
            lines.append(f'"{c["name"]}" [label="{c["name"]}\\n«{c["stereotype"]}»"];')
        lines.append("}")
    for r in chosen:
        for s in ends(r["source"]):
            targets = [t for t in ends(r["target"]) if t in pkg_of]
            packages = {pkg_of[t] for t in targets}
            if len(targets) > 1 and len(packages) == 1:
                # one edge to the cluster instead of one per union member
                middle = targets[len(targets) // 2]   # aim at the centre so the edge visibly hits the cluster
                lines.append(f'"{s}" -> "{middle}" [label="{r["name"]}", lhead="cluster_{packages.pop()}"];')
            else:
                for t in targets:
                    lines.append(f'"{s}" -> "{t}" [label="{r["name"]}"];')
    lines.append("}")
    return "\n".join(lines)


