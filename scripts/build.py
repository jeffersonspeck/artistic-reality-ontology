def html_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_ontouml_dot(cat: dict, package: str | None) -> str:
    colors = {p["name"]: p["color"] for p in cat["packages"]}
    by_name = {c["name"]: c for c in cat["classes"]}
    shown = [c for c in cat["classes"] if package is None or c["package"] == package]
    names = {c["name"] for c in shown}
    # neighbours from other packages are drawn faded so package views stay readable
    context = set()
    if package:
        for r in cat["relations"]:
            ends = ([r["source"]] if isinstance(r["source"], str) else r["source"]) + \
                   ([r["target"]] if isinstance(r["target"], str) else r["target"])
            if names & set(ends):
                context |= {e for e in ends if e in by_name and e not in names}
        for c in shown:
            context |= {sup for sup in parents(c) if sup not in names}
    attrs = {}
    for d in cat.get("datatype_properties", []):
        doms = [d["domain"]] if isinstance(d.get("domain"), str) else (d.get("domain") or [])
        for dom in doms:
            attrs.setdefault(dom, []).append(f'{d["name"]} : {d["range"].split(":")[-1]}')

    def box(c, faded=False):
        colour = "#f8fafc" if faded else colors[c["package"]]
        title = f'<I>{html_escape(c["name"])}</I>' if c.get("abstract") else html_escape(c["name"])
        note = '<BR/><FONT POINT-SIZE="8">{abstract}</FONT>' if c.get("abstract") else ""
        rows = [f'<TR><TD BGCOLOR="{colour}"><FONT POINT-SIZE="9">«{c["stereotype"]}»</FONT><BR/>'
                f'<B>{title}</B>{note}</TD></TR>']
        if not faded:
            body = "".join(f'{html_escape(a)}<BR ALIGN="LEFT"/>' for a in attrs.get(c["name"], [])) or " "
            rows.append(f'<TR><TD ALIGN="LEFT" BALIGN="LEFT" BGCOLOR="white"><FONT POINT-SIZE="9">{body}</FONT></TD></TR>')
        border = "#94a3b8" if faded else "#334155"
        return (f'"{c["name"]}" [shape=plain, label=<<TABLE BORDER="1" COLOR="{border}" CELLBORDER="0" '
                f'CELLSPACING="0" CELLPADDING="4">{"".join(rows)}</TABLE>>];')

    lines = [f"// {GENERATED_NOTE}", "digraph ontouml {",
             f'graph [rankdir={ONTOUML_RANKDIR.get(package, "BT")}, bgcolor="white", pad="0.4", nodesep="0.5", ranksep="0.8", '
             'fontname="Arial", fontsize=14, labeljust="l", newrank=true, splines=true];',
             'node [fontname="Arial", fontsize=10];',
             'edge [fontname="Arial", fontsize=8, color="#475569", arrowsize=0.7];']
    if package is None:
        for p in cat["packages"]:
            members = [c for c in shown if c["package"] == p["name"]]
            lines.append(f'subgraph "cluster_{p["name"]}" {{ label=<<B>{p["label_en"]}</B>>; style="rounded,dashed,filled"; '
                         f'fillcolor="#fcfcfd"; color="#94a3b8";')
            lines += [box(c) for c in members]
            lines.append("}")
    else:
        lines += [box(c) for c in shown]
        lines += [box(by_name[n], faded=True) for n in sorted(context)]
    drawn = names | context
    externals = set()
    for r in cat["relations"]:
        sources = [r["source"]] if isinstance(r["source"], str) else r["source"]
        targets = [r["target"]] if isinstance(r["target"], str) else r["target"]
        union = len(targets) > 1
        for s in sources:
            if s not in drawn:
                continue
            for t in targets:
                # in a package view, keep relations that touch the package (either end)
                if package is not None and s not in names and t not in names:
                    continue
                if t not in by_name:
                    externals.add(t)
                elif t not in drawn:
                    continue
                stereo = f'«{r["ontouml"]}»\\n' if r.get("ontouml") else ""
                note = " {union}" if union else ""
                # in the overview, relations between packages are lighter than those inside one
                across = package is None and t in by_name and by_name[s]["package"] != by_name[t]["package"]
                colour = ', color="#94a3b8", fontcolor="#64748b"' if across else ""
                lines.append(f'"{s}" -> "{t}" [label="{stereo}{r["name"]}{note}", taillabel="{r["source_cardinality"]}", '
                             f'headlabel="{r["target_cardinality"]}", arrowhead=open, labelfontsize=8{colour}];')
    for e in sorted(externals):
        lines.append(f'"{e}" [shape=box, style="rounded,dashed", color="#94a3b8", fontcolor="#475569", label="{e}\\n(external)"];')
    for c in shown:
        for sup in parents(c):
            if sup in drawn:
                # generalizations into another package are drawn lighter (in the overview, most
                # analytical records specialize AnalyticalRecord in the claims package)
                across = package is None and by_name[sup]["package"] != c["package"]
                colour = "#94a3b8" if across else "#0f172a"
                lines.append(f'"{c["name"]}" -> "{sup}" [arrowhead=empty, arrowsize=1.1, color="{colour}"];')
    lines.append("}")
    return "\n".join(lines)


# ------------------------------------------------------------ OntoUML exchange
# The model as an OntoUML project in the official JSON format (OntoUML Schema 1.0.2,
# https://w3id.org/ontouml/schema), so it can be validated, verified (scripts/verify_ontouml.py)
# and opened in OntoUML tools (ADR-009). Classes, generalizations and associations are exported;
# datatype attributes and external classes (oa:Selector) are not part of the OntoUML model.
ONTOUML_JSON = "model/ontouml/aro.ontouml.json"
ONTOUML_CREATED = "2026-10-30"          # creation date of the model (first release)
# OntoUML "restrictedTo": the ontological nature of the instances of each stereotype
NATURE = {"kind": ["functional-complex"], "subkind": None, "role": None, "collective": ["collective"],
          "relator": ["relator"], "event": ["event"], "situation": ["situation"], "type": ["type"],
          "category": None, "roleMixin": None}


def build_ontouml_json(cat: dict) -> str:
    by_name = {c["name"]: c for c in cat["classes"]}

    def up(name: str) -> list[str]:
        """A sortal's nature comes from its ultimate sortal, found up the specialization chain."""
        c = by_name[name]
        if NATURE[c["stereotype"]]:
            return NATURE[c["stereotype"]]
        return [n for p in parents(c) if by_name[p]["stereotype"] not in ("category", "roleMixin") for n in up(p)]

    def down(name: str) -> list[str]:
        """A non-sortal is restricted to the natures of the sortals that specialize it."""
        out = []
        for k in cat["classes"]:
            if name in parents(k):
                out += down(k["name"]) if k["stereotype"] in ("category", "roleMixin") else up(k["name"])
        return out

    def nature(name: str) -> list[str]:
        c = by_name[name]
        return sorted(set(down(name) if c["stereotype"] in ("category", "roleMixin") else up(name)))

    def lang_string(en: str, pt: str) -> dict:
        return {"en": en, "pt-BR": pt}

    def element(kind: str, ident: str, name: dict | None, description: dict | None, **extra) -> dict:
        e = {"type": kind, "id": ident, "created": ONTOUML_CREATED, "modified": None,
             "name": name, "alternativeNames": [], "description": description, "editorialNotes": [],
             "creators": [], "contributors": []}
        e.update(extra)
        return e

    model_element = {"customProperties": None}
    elements, package_contents = [], {p["name"]: [] for p in cat["packages"]}
    for c in cat["classes"]:
        e = element("Class", f"class-{c['name']}", {"en": c["name"]},
                    lang_string(c["definition_en"], c["definition_pt"]), **model_element,
                    stereotype=c["stereotype"], isDerived=False, isAbstract=bool(c.get("abstract")) or c["stereotype"] in ("category", "roleMixin"),
                    properties=[], literals=[], restrictedTo=nature(c["name"]), isPowertype=False,
                    order="2" if c["stereotype"] == "type" else "1")
        e["alternativeNames"] = [lang_string(c["label_en"], c["label_pt"])]
        elements.append(e)
        package_contents[c["package"]].append(e["id"])
        for sup in parents(c):
            g = element("Generalization", f"gen-{c['name']}-{sup}", None, None, **model_element,
                        general=f"class-{sup}", specific=f"class-{c['name']}")
            elements.append(g)
            package_contents[c["package"]].append(g["id"])
    for r in cat["relations"]:
        if r["source"] not in by_name or r["target"] not in by_name:
            continue                       # relations to external classes stay outside the OntoUML model
        ends = []
        for side, cls, card in (("source", r["source"], r["source_cardinality"]), ("target", r["target"], r["target_cardinality"])):
            prop = element("Property", f"rel-{r['name']}-{side}", None, None, **model_element,
                           stereotype=None, isDerived=False, subsettedProperties=[], redefinedProperties=[],
                           aggregationKind="NONE", cardinality=card, isOrdered=False, isReadOnly=False,
                           propertyType=f"class-{cls}")
            elements.append(prop)
            ends.append(prop["id"])
        rel = element("BinaryRelation", f"rel-{r['name']}", {"en": r["name"]},
                      lang_string(r["definition_en"], r["definition_pt"]), **model_element,
                      stereotype=r.get("ontouml"), isDerived=False, isAbstract=False, properties=ends)
        rel["alternativeNames"] = [lang_string(r["description_en"], r["description_pt"])]
        elements.append(rel)
        package_contents[by_name[r["source"]]["package"]].append(rel["id"])
    packages = []
    for p in cat["packages"]:
        packages.append(element("Package", f"package-{p['name']}", lang_string(p["label_en"], p["label_pt"]),
                                lang_string(p["description_en"], p["description_pt"]), **model_element,
                                contents=package_contents[p["name"]]))
    root = element("Package", "package-aro", {"en": "ARO"}, None, **model_element,
                   contents=[p["id"] for p in packages])
    meta = cat["ontology"]
    project = element("Project", "project-aro", lang_string(meta["title_en"], meta["title_pt"]),
                      lang_string(meta["description_en"], meta["description_pt"]),
                      elements=[root] + packages + elements, root="package-aro", publisher=None,
                      designedForTasks=[], license={"URI": "https://opensource.org/licenses/MIT", "name": {"en": "MIT"}},
                      accessRights=[], themes=[], contexts=[], ontologyTypes=[],
                      representationStyle=None, namespace=str(ARO), landingPages=[], sources=[],
                      bibliographicCitations=[], keywords=[], acronyms=["ARO"], languages=["en", "pt-BR"])
    project["creators"] = [{"URI": None, "name": {"en": meta["creator"]}}]
    return json.dumps(project, ensure_ascii=False, indent=2) + "\n"


