def class_usage(cat: dict, name: str) -> tuple[list[str], list[str], list[str]]:
    """Properties having the class in their domain or range, and SHACL constraints targeting it."""
    def has(ref):
        return ref == name or (isinstance(ref, list) and name in ref)
    domain = [r["name"] for r in cat["relations"] if has(r["source"])]
    domain += [d["name"] for d in cat.get("datatype_properties", []) if has(d.get("domain"))]
    rng = [r["name"] for r in cat["relations"] if has(r["target"])]
    shacl = [(r, r["shacl"]) for r in cat["relations"] if r["source"] == name and r.get("shacl")]
    shacl += [(r, r["shacl_by_class"][name]) for r in cat["relations"] if name in r.get("shacl_by_class", {})]
    return domain, rng, shacl


def turtle_snippet(onto: Graph, name: str) -> str:
    """The class's own triples from the generated ontology, without @prefix lines."""
    sub = bind(Graph())
    for triple in onto.triples((ARO[name], None, None)):
        sub.add(triple)
    lines = sub.serialize(format="turtle").splitlines()
    return "\n".join(l for l in lines if not l.startswith("@prefix")).strip()


def build_reference_doc(cat: dict, lang: str) -> str:
    """Render reference-model.md (classes, relations, datatype properties, vocabularies) in one language.

    Each class shows its definition, what its stereotype means in UFO, how it is
    represented in OWL/TTL (with its actual Turtle), its SHACL constraints and what the
    OWL projection cannot express.
    """
    t = DOC_TEXT[lang]
    rows = CLASS_ROWS[lang]
    suffix = "en" if lang == "en" else "pt"   # catalog field suffix for this language
    onto = build_ontology(cat)
    out = [t["generated"], "", t["nav"], "", t["title"], "", t["intro"], ""]

    # Summary: one row per stereotype in use
    out += [rows["stereo_title"], "", rows["stereo_head"], "|---|---|---|---|---|"]
    for st, info in STEREOTYPES.items():
        members = [c["name"] for c in cat["classes"] if c["stereotype"] == st]
        if members:
            out.append(f"| «{st}» | {', '.join(f'`{m}`' for m in members)} | {info['ufo_' + suffix]} | "
                       f"{info['owl_' + suffix]} | {info['gap_' + suffix]} |")
    out += ["", "## Classes", ""]

    for c in cat["classes"]:
        info = STEREOTYPES[c["stereotype"]]
        domain, rng, shacl = class_usage(cat, c["name"])
        owl = [f"`aro:{c['name']} a owl:Class`"]
        for sup in parents(c):
            owl.append(f"`rdfs:subClassOf aro:{sup}`")
        if len(parents(c)) > 1:
            owl.append("`owl:equivalentClass` " + " ⊓ ".join(f"`aro:{x}`" for x in parents(c)))
        if c.get("abstract"):
            kids = [k["name"] for k in cat["classes"] if c["name"] in parents(k) and k["stereotype"] in RIGID_SORTALS]
            owl.append(f"{rows['abstract']}: `owl:disjointUnionOf` (" + ", ".join(f"`aro:{k}`" for k in kids) + ")")
        if c["stereotype"] in ULTIMATE_SORTALS:
            owl.append(rows["disjoint"])
        if info.get("note_" + suffix):              # stereotype-specific projection detail
            owl.append(info["note_" + suffix])
        if domain:
            owl.append(f"{rows['domain']}: " + ", ".join(f"`{x}`" for x in domain))
        if rng:
            owl.append(f"{rows['range']}: " + ", ".join(f"`{x}`" for x in rng))
        constraints = []
        for r, s in shacl:
            parts = [f"{rows['min']} {s['minCount']}" if "minCount" in s else "",
                     f"{rows['max']} {s['maxCount']}" if "maxCount" in s else "",
                     f"{rows['class']} `{s['class']}`" if "class" in s else "",
                     rows["iri"] if s.get("nodeKind") == "IRI" else ""]
            constraints.append(f"`{r['name']}` ({', '.join(p for p in parts if p)})")
        constraints += [f"SPARQL: {x['message_' + suffix]}" for x in cat.get("sparql_constraints", [])
                        if x["target"] == c["name"]]
        gap = info["gap_" + suffix]
        gufo = info["gufo"]
        if c["stereotype"] == "kind" and "information" in c["grounding_en"]:
            gufo += f" — {rows['info']}"

        out += [f"### `{c['name']}` — {c[t['label_key']]}", "",
                f"**{t['definition']}:** {c[t['def_key']]}", "",
                "| | |", "|---|---|",
                f"| **{rows['ufo']}** | «{c['stereotype']}» — {info['ufo_' + suffix]} |",
                f"| **{rows['grounding']}** | {c['grounding_' + suffix]} |",
                f"| **{rows['dependency']}** | {c['dependency_' + suffix]} |",
                f"| **{rows['owl']}** | {'; '.join(owl)} |",
                f"| **{rows['shacl']}** | {'; '.join(constraints) if constraints else '—'} |",
                f"| **{rows['gap']}** | {gap} |",
                f"| **{rows['gufo']}** | {gufo} |"]
        if c.get("alignments"):
            al = ", ".join(f"`{p}` `{x}`" for p, xs in c["alignments"].items() for x in xs)
            out.append(f"| **{t['alignments']}** | {al} |")
        out += [f"| **{t['package']}** | `{c['package']}` |", "",
                "<details>", f"<summary>{rows['turtle']}</summary>", "", "```turtle",
                turtle_snippet(onto, c["name"]), "```", "", "</details>", ""]
    # Relation table (column headers stay in English in both versions, as in the original docs)
    out += [t["relations"], "",
            "| Relation | Source → target | Multiplicity at target | Meaning |",
            "|---|---|---|---|"]
    for r in cat["relations"]:
        out.append(f"| `{r['name']}` | {fmt_ref(r['source'])} → {fmt_ref(r['target'])} | "
                   f"`{r['target_cardinality']}` | **{r[t['desc_key']]}.** {r['definition_' + suffix]} |")
    dps = cat.get("datatype_properties", [])
    if dps:
        out += ["", t["datatypes"], "", "| Property | Label | Domain | Datatype | Meaning |", "|---|---|---|---|---|"]
        for d in dps:
            dom = fmt_ref(d["domain"]) if d.get("domain") else "—"
            out.append(f"| `{d['name']}` | {d[t['label_key']]} | {dom} | `{d['range']}` | {d['comment_' + suffix]} |")
    # One table per SKOS scheme, including the literature behind each concept
    for scheme in cat.get("concept_schemes", []):
        out += ["", t["schemes"], "", f"### `{scheme['name']}` — {scheme[t['label_key']]}", ""]
        if scheme.get(t["def_key"]):
            out += [scheme[t["def_key"]], ""]
        out += [f"| {t['concept']} | {t['label']} | {t['broader']} | {t['definition']} | {t['source']} |",
                "|---|---|---|---|---|"]
        for c in scheme["concepts"]:
            broader = f"`{c['broader']}`" if c.get("broader") else "—"
            out.append(f"| `{c['name']}` | {c[t['label_key']]} | {broader} | {c[t['def_key']]} | {c.get('source', '—')} |")
    out += ["", "---", "", t["nav"]]
    return "\n".join(out) + "\n"


