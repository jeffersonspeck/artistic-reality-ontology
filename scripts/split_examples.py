"""Split examples/case-studies.ttl into one self-contained file per work.

Usage:
  python scripts/split_examples.py          # write examples/example_<work>.ttl
  python scripts/split_examples.py --check  # exit 1 if the split files are out of date

examples/case-studies.ttl (all works together) remains the source; each
examples/example_<work>.ttl contains what belongs to one work, found by walking the graph
from the artwork with the rules in `work_scope` (the annotator uses the same rules to
show or hide works). Patterns, cases and sources shared by several works are copied into
every file that uses them, so each file validates and can be loaded on its own.
"""
from __future__ import annotations

import sys
from pathlib import Path

from rdflib import Graph, Namespace, URIRef
from rdflib.namespace import RDF, SKOS

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "examples/case-studies.ttl"
ARO = Namespace("https://w3id.org/aro/ontology#")

# Works to extract: output name -> artwork IRI
WORKS = {
    "example_homem_na_estrada": URIRef("https://example.org/aro-cases/homem-na-estrada"),
    "example_vidas_secas": URIRef("https://example.org/aro-cases/vidas-secas"),
}

# Nodes reached through these classes are included but only their outgoing relations are
# followed, so a shared node does not pull in the other works that also point to it.
OUTGOING_ONLY = {ARO.InterpretiveAct, ARO.ReferenceSource}
# A situation pattern is shared across works: from it, follow only its conditions and the
# claims/hypotheses about it, not the situations of other works that generalize to it.
PATTERN_INCOMING = {ARO.assertsPattern, ARO.explainsPattern}


def work_scope(g: Graph, start: URIRef) -> set:
    """Every node that belongs to the work `start` (see module docstring for the rules)."""
    seen, stack = {start}, [start]
    while stack:
        node = stack.pop()
        types = set(g.objects(node, RDF.type))
        if node != start and ARO.Artwork in types:
            continue                      # another work: keep the node, do not enter it
        if node.startswith(str(ARO)):
            continue                      # vocabulary concept defined by the ontology
        nxt = [o for _, p, o in g.triples((node, None, None)) if isinstance(o, URIRef) and p != RDF.type]
        if ARO.SituationPattern in types:
            nxt += [s for s, p, _ in g.triples((None, None, node)) if p in PATTERN_INCOMING]
        elif not types & OUTGOING_ONLY:
            nxt += [s for s, _, _ in g.triples((None, None, node))]
        for n in nxt:
            if n not in seen:
                seen.add(n)
                stack.append(n)
    return seen


def extract(g: Graph, start: URIRef) -> Graph:
    """All triples whose subject belongs to the work."""
    scope = work_scope(g, start)
    out = Graph()
    for prefix, ns in g.namespaces():
        out.bind(prefix, ns)
    for s, p, o in g:
        if s in scope:
            out.add((s, p, o))
    return out


def header(name: str, g: Graph, start: URIRef) -> str:
    title = next((str(t) for t in g.objects(start, ARO.textValue) if getattr(t, "language", None) == "pt-br"
                  or getattr(t, "language", None) == "pt-BR"), str(start))
    return (f"# {name}.ttl — {title}\n"
            "# Generated by scripts/split_examples.py from examples/case-studies.ttl (all works).\n"
            "# Do not edit by hand: edit case-studies.ttl and run the script again.\n"
            "# Lyrics and novel text are not stored; see docs/*/case-studies.md for the method.\n")


def main() -> int:
    check = "--check" in sys.argv
    g = Graph().parse(SOURCE)
    stale = []
    for name, start in WORKS.items():
        text = header(name, g, start) + extract(g, start).serialize(format="turtle")
        path = ROOT / "examples" / f"{name}.ttl"
        if path.exists():
            from rdflib.compare import isomorphic
            if isomorphic(Graph().parse(path), Graph().parse(data=text, format="turtle")):
                continue
        stale.append(path.name)
        if not check:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("Out of date (run python scripts/split_examples.py): " + ", ".join(stale))
            return 1
        print("Split examples are up to date.")
        return 0
    print("Wrote: " + (", ".join(stale) if stale else "nothing (up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
