// SPARQL in the browser: runs the competency-question (CQ) and research-question (RQ)
// queries of queries/*.rq over the user's annotations plus the ontology, as
// scripts/query.py does in Python. Engine: Oxigraph (WebAssembly), loaded on first use.

const OXIGRAPH = "https://cdn.jsdelivr.net/npm/oxigraph@0.4.11/web.js";
let engine = null;

/** Load and initialise Oxigraph once. */
async function loadEngine() {
  if (!engine) {
    const module = await import(OXIGRAPH);
    await module.default();      // initialise the WebAssembly module
    engine = module;
  }
  return engine;
}

/** The list of queries (queries/index.json, generated by scripts/build.py). */
export async function queryIndex() {
  const response = await fetch("../queries/index.json");
  if (!response.ok) throw new Error("queries/index.json");
  return (await response.json()).queries;
}

/** Text of one query file. */
export async function queryText(file) {
  const response = await fetch(`../queries/${file}`);
  if (!response.ok) throw new Error(file);
  return response.text();
}

/**
 * Run a SELECT query over the annotations (Turtle) and the ontology (Turtle).
 * Returns {vars: [names], rows: [[{value, termType, language}]]}.
 */
export async function runSelect(sparql, dataTurtle, ontologyTurtle) {
  const ox = await loadEngine();
  const store = new ox.Store();
  // the ontology supplies labels and class hierarchy used by several queries
  store.load(ontologyTurtle, { format: "text/turtle", base_iri: "https://w3id.org/aro/ontology" });
  store.load(dataTurtle, { format: "text/turtle", base_iri: "https://example.org/" });
  const results = store.query(sparql);
  if (!Array.isArray(results)) throw new Error("Only SELECT queries are supported here.");
  const vars = [];
  const rows = results.map((binding) => {
    const row = {};
    for (const [name, term] of binding) {
      if (!vars.includes(name)) vars.push(name);
      row[name] = term;
    }
    return row;
  });
  // Column order = the SELECT clause; "(expression AS ?x)" counts as ?x. Variables that
  // are never bound still get a column (empty cells), like in scripts/query.py.
  const head = /SELECT\s+(?:DISTINCT\s+|REDUCED\s+)?([\s\S]*?)\s*(?:FROM|WHERE|\{)/i.exec(sparql);
  let declared = [];
  if (head && head[1].trim() !== "*") {
    const clause = head[1].replace(/\((?:[^()]|\([^()]*\))*?\bAS\s+\?(\w+)\s*\)/gi, "?$1");
    declared = [...clause.matchAll(/\?(\w+)/g)].map((m) => m[1]);
  }
  const order = [...new Set([...declared, ...vars])];
  return { vars: order, rows: rows.map((r) => order.map((v) => r[v] || null)) };
}
